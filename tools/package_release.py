"""构建 Windows x64 发布包：可执行文件 + 完整源码。

仓库根即打包根。本脚本先 chdir 到仓库根（``paths.REPO_ROOT``），之后所有相对路径
都以它为基准：``pbb/``、``tools/``、``fonts/``、``assets/``、``offline/``、``docs/``、
``config/`` 以及根目录的入口文件。运行前请先看 ``check_inputs()``。

产物布局（发布包）::

    PBB/
      main.py  ui.py                 ← 薄启动器
      source/pbb/  source/tools/     ← 完整源码，可自行 rebuild
      source/tests/                  ← 离线包验证会跑它们
      config/                        ← 唯一一份可编辑配置
      PBBMonitor/                    ← 冻结的图形监控器
"""
import json
import os
from pathlib import Path
import re
import subprocess
import sys
from datetime import datetime

# 本文件在 tools/ 下，需要把仓库根加入 sys.path 才能 import pbb 包。
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from pbb import _build as build
from pbb import build_settings, paths

from _archive import write_zip_atomic

ROOT = paths.REPO_ROOT

DIST_DIR = "dist_releases/" + datetime.now().strftime("%Y%m%d_%H%M%S_%f")
CONFIG_NAMES = {'build_config.json', 'config.yaml', 'config.json', 'config.toml',
                'config_football.yaml', 'config.example.yaml', 'config.example.json', 'config.example.toml',
                'config_flex.example.yaml', 'config_words_sequential.yaml'}
CHARSET_NAMES = ('adjectives.txt', 'nouns.txt', 'adverbs.txt', 'verbs.txt')

# 文档目录：AUTOTUNE.md、PACKAGING.md 等开发/打包说明放在这里。
DOCS_DIR = "docs"
# 面向用户的两份说明放在根目录：Markdown 是版本控制的真源，PDF 由外部工具导出，
# 两者都直接进入发布包顶层（PBB/README.md、PBB/先读我.md 及其 PDF）。
PDF_SOURCES = (("README.md", "README.pdf"),
               ("先读我.md", "先读我.pdf"))
# PDF 不由本仓库生成，缺失时给出可直接照做的导出命令。
PDF_HINT = ('Export it with a Markdown-to-PDF tool and keep it at the repository root, e.g.\n'
            '  pandoc "{source}" -o "{pdf}" --pdf-engine=xelatex -V CJKmainfont="Sarasa Mono SC"\n'
            '  npx md-to-pdf "{source}"     # needs a CJK-capable font for the Chinese text\n'
            '  python -m markdown_pdf "{source}" -o "{pdf}"')
# 图标资源目录（pbb/ui.py 与 tools/PBBMonitor.spec 都从这里取）。
ASSETS_DIR = "assets"
SPEC_FILE = "tools/PBBMonitor.spec"


def _describe(items):
    """把路径集合排成稳定的多行文本，用于报错信息。"""
    return "\n".join(f"  - {item}" for item in sorted(set(map(str, items))))


def check_inputs():
    """在编译前先做输入预检，失败即退出，避免编译几分钟后才报错。

    所有路径都以仓库根（``paths.REPO_ROOT``）为基准解析，因此在 main() 里 chdir 之前
    调用也能正确判断，且不受调用者当前工作目录影响。
    """
    missing_md = [md for md, _ in PDF_SOURCES if not (ROOT / md).is_file()]
    missing_pdf = [pdf for _, pdf in PDF_SOURCES if not (ROOT / pdf).is_file()]
    if missing_md:
        raise SystemExit("Missing documentation source, cannot determine what to export:\n"
                         + _describe(missing_md) + "\nRestore the Markdown file before packaging.")
    if missing_pdf:
        detail = "\n\n".join(PDF_HINT.format(source=md, pdf=pdf)
                             for md, pdf in PDF_SOURCES if not (ROOT / pdf).is_file())
        raise SystemExit(
            "Missing exported PDF release input:\n" + _describe(missing_pdf)
            + "\n\nThe PDFs are not generated by this repository; they are exported from the\n"
              "Markdown files with an external tool. Export them, then run this script again.\n\n"
            + detail)
    required = ("pbb", "tools", "fonts", "assets", "offline", "charsets", SPEC_FILE,
                "main.py", "ui.py", *[md for md, _ in PDF_SOURCES])
    missing = [name for name in required if not (ROOT / name).exists()]
    if missing:
        raise SystemExit(
            "These release inputs do not exist:\n" + _describe(missing)
            + "\n\nRun this script from the repository root, which is the packaging root:\n"
              "pbb/, tools/, fonts/, assets/, offline/, docs/ and config/ live here.")


def distribution_configs():
    """生成发布包 config/ 目录里的全部配置内容（名称 → 字节内容）。"""
    config_dir = build_settings.config_root(ROOT)
    # 除 config.yaml 与 build_config.json 外的配置：示例、足球配置等，按原样带出。
    configs = {name: source_payload(config_dir / name) for name in CONFIG_NAMES
               if name not in ('config.yaml', 'config.json', 'config.toml', 'build_config.json')
               and (config_dir / name).is_file()}
    if not (config_dir / 'config_football.yaml').is_file():
        raise SystemExit(f"Missing {config_dir / 'config_football.yaml'}: the shipped config.yaml is generated from it.")
    # 发布的 config.yaml 由足球配置生成（README.md 有说明）。
    configs['config.yaml'] = (config_dir / 'config_football.yaml').read_bytes()
    # 始终带出一份「未测试」的 build_config.json：本机那份可能不存在
    # （开发仓库只保留 build_config.fresh.json），也可能带着本机的测速结论，
    # 那种结论绝不能带到别的 CPU 上。
    configs['build_config.json'] = source_payload(config_dir / 'build_config.json')
    return configs


def stage_configs(root):
    """把可编辑配置集中到外层 config/ 目录，并清掉其它位置的同名副本。

    ``root`` 是外层包根。开发仓库里它就是仓库根；发布布局里源码在 ``root/source``。
    两种形态都清理一遍，保证归档里不会残留第二份可编辑配置。
    """
    (root / 'config').mkdir(parents=True, exist_ok=True)
    for name, data in distribution_configs().items():
        (root / 'config' / name).write_bytes(data)
    (root / 'charsets').mkdir(parents=True, exist_ok=True)
    for name, data in distribution_charsets().items():
        (root / 'charsets' / name).write_bytes(data)
    for directory in (root, root / 'source', root / 'PBBMonitor/_internal'):
        for name in CONFIG_NAMES:
            (directory / name).unlink(missing_ok=True)


def distribution_charsets():
    """随外层词族配置提供一份词库，保持../charsets/相对路径可用。"""
    return {name: (ROOT / 'charsets' / name).read_bytes() for name in CHARSET_NAMES}


def check_entry_points() -> None:
    """校验"批处理脚本引用的源码入口"确实存在，并在打包清单里。

    这是从一次真实事故总结出来的：``tune_full.bat`` 当时指向 ``tools/tune.py``，
    但那个文件根本不存在 —— 开发仓库里没人执行那条路径，直到用户双击才报
    "can't open file ... tools\\tune.py"。所以把"脚本 → 目标"的引用关系显式建模，
    在打包前逐个核对，让同类问题在构建期自曝，而不是留给用户。

    解析方式是保守的：只认 ``.py`` 字面量，跳过含 ``%`` 的变量（那种要在运行时展开），
    并把相对路径按脚本所在位置解析（发布包里脚本在 ``<包根>/source/`` 下）。
    """
    referenced: dict[str, set[str]] = {}
    for script in sorted(Path("offline").glob("*.bat")) + sorted(Path(".").glob("*.bat")):
        text = script.read_text(encoding="utf-8", errors="replace")
        for token in re.findall(r"[\w\\/.\-]+\.py", text):
            token = token.replace("\\", "/")
            # 跳过需要在运行时展开的东西：%VAR% 变量，以及经由 %~dp0 拼接的路径
            # （%~dp0 里的 "0" 会把 dp0 一起带进匹配结果，这类路径以 dp0 开头）。
            if "%" in token or token.startswith("dp0"):
                continue
            referenced.setdefault(token, set()).add(script.name)

    packaged = {str(p).replace("\\", "/") for p in source_paths()}
    # 打包脚本之间会互相 import（package_offline 用 package_release 的白名单、
    # 两者都用 _archive 的原子写盘），这些运行时依赖必须一起进包。
    for module in ("tools/package_release.py", "tools/package_offline.py", "tools/_archive.py"):
        if (ROOT / module).is_file() and module not in packaged:
            packaged.add(module)
    missing_on_disk = [t for t in referenced if not (ROOT / t).is_file()]
    missing_from_pack = sorted(t for t in referenced if t not in packaged)

    if missing_on_disk:
        raise SystemExit(
            "These launcher scripts reference source entries that do not exist:\n"
            + _describe(f"{target}  (referenced by {', '.join(sorted(referenced[target]))})"
                        for target in missing_on_disk))
    if missing_from_pack:
        raise SystemExit(
            "These launcher targets exist but are missing from source_paths(), so they would\n"
            "not be shipped inside the release archive:\n"
            + _describe(f"{target}  (referenced by {', '.join(sorted(referenced[target]))})"
                        for target in missing_from_pack))
    print(f"Launcher entry-point check passed ({len(referenced)} referenced .py targets).")


def source_paths():
    """列出要打进发布包 ``source/`` 的源码与资源路径（相对仓库根）。"""
    # 整棵带出：Python 包（含 C++ 源码 pbb/native/）、工具、字体、发布包根目录模板。
    paths = (list(Path("pbb").rglob("*")) + list(Path("tools").rglob("*"))
             + list(Path("fonts").rglob("*")) + list(Path("offline").rglob("*")))
    paths += [Path(name) for name in (
        # 顶层薄启动器与文档。
        "main.py", "ui.py", "README.md", "PACKAGING.md", "docs/AUTOTUNE.md", "docs/FLEX.md",
        # 测试：离线包验证会跑整套。
        "tests/test_autotune.py", "tests/test_build.py", "tests/test_build_settings.py",
        "tests/test_config_location.py", "tests/test_docstring_coverage.py",
        "tests/test_ui_affixes.py", "tests/test_ui_drag.py", "tests/test_ui_engine.py", "tests/test_flex.py",
        "tests/test_qp_filter.py", "tests/native_qp_filter.cpp", "tests/test_threading_config.py",
        "tests/test_ui_start.py",
        "tests/test_distribution_configs.py",
        "tests/test_progress_safety.py",
        # 发布包内的自动测速入口与开发入口。
        "tune_quick.bat", "tune_full.bat", "run.bat", "run.sh", "run_ui.bat",
        # 配置模板（发布包 config/ 由 distribution_configs() 统一生成，这里只在源码目录留示例）。
        "config.example.yaml", "config.example.json", "config.example.toml",
        "config_football.yaml",
    )]
    return [path for path in paths
            if path.is_file() and "__pycache__" not in path.parts and path.suffix != ".pyc"]


def source_payload(path):
    """读取单个文件的发布内容；build_config.json 一律换成未测试的默认值。"""
    # 绝不把本机的测速结论发给别的 CPU。
    return (json.dumps(build_settings.fresh(), indent=2) + '\n').encode() \
        if path.name == 'build_config.json' else path.read_bytes()


def check_frozen_monitor(monitor: Path) -> None:
    """对刚冻结出来的监控器做启动自检：``PBBMonitor.exe --check``。

    为什么必须做：PyInstaller 打包成功只说明文件收集齐了，**不说明能跑起来**。
    冻结后入口脚本以 ``__main__`` 身份执行、没有包上下文，任何相对导入都会在运行时
    才报 ImportError；这类问题只有真正启动一次才暴露。

    判据（windowed 构建拿不到 stdout/stderr，所以用文件传递结果）：
      - 进程正常退出且 ``.gui_check_ok`` 出现 ⇒ 通过；
      - 超时（坏包会静默挂住，不会自己退出）或非零退出 ⇒ 失败，读 ``.gui_check_error.log``。
    失败即中断打包，避免把跑不起来的监控器放进发布包。
    """
    exe = monitor / "PBBMonitor.exe"
    if not exe.is_file():
        raise SystemExit(f"Frozen monitor entry not found: {exe}")
    ok_marker = monitor / ".gui_check_ok"
    error_log = monitor / ".gui_check_error.log"
    for stale in (ok_marker, error_log):
        stale.unlink(missing_ok=True)

    timed_out = False
    try:
        result = subprocess.run([str(exe), "--check"], cwd=monitor,
                                capture_output=True, timeout=120)
        returncode = result.returncode
    except subprocess.TimeoutExpired:
        # 崩溃的 windowed 构建不会退出，只会挂住 —— 超时本身就是失败信号。
        timed_out, returncode = True, None
    except OSError as exc:
        raise SystemExit(f"Could not start the frozen monitor for its startup check: {exc}")

    detail = ""
    if error_log.is_file():
        detail = "\n--- .gui_check_error.log ---\n" + error_log.read_text(
            encoding="utf-8", errors="replace").strip()[-4000:]

    if returncode == 0 and ok_marker.is_file():
        # 自检产物不随包分发。
        for leftover in (ok_marker, error_log):
            leftover.unlink(missing_ok=True)
        print("Frozen monitor startup check passed (--check).")
        return

    reason = ("timed out after 120s (the frozen monitor hung instead of exiting)"
              if timed_out else f"exited with code {returncode}")
    raise SystemExit(
        f"Frozen monitor failed its startup check: {reason}.{detail}\n\n"
        f"Reproduce manually:\n  cd \"{monitor}\" && PBBMonitor.exe --check")


def main():
    if sys.platform != "win32":
        raise SystemExit("This release script targets Windows x64")
    os.chdir(ROOT)
    check_inputs()
    check_entry_points()
    # 发布引擎必须用保守指令集，且不接受外部编译参数覆盖。
    os.environ["PBB_BUILD_MODE"] = "portable"
    os.environ.pop("PBB_SRC_DIR", None)
    os.environ.pop("PBB_CXXFLAGS", None)
    build._compile_pbb_core(verbose=True)
    build._compile_engine(verbose=True)
    build._compile_engine(output_path=str(paths.engine_binary(ui=True)), ui_engine=True)
    subprocess.run([sys.executable, "-m", "PyInstaller", "--noconfirm",
                    "--distpath", DIST_DIR, "--workpath", "release_build",
                    SPEC_FILE], check=True)
    monitor = Path(DIST_DIR) / "PBBMonitor"
    if not monitor.is_dir():
        raise SystemExit(f"PyInstaller did not produce {monitor}; see the PyInstaller output above.")
    check_frozen_monitor(monitor)
    release = Path("release")
    release.mkdir(exist_ok=True)

    # 组装 pure 包：监控器目录 + 源码 + 配置 + 外壳脚本，全部放进 PBB/ 前缀。
    # write_zip_atomic 负责"先写临时文件再原子替换 + 锁重试"，见 tools/_archive.py。
    def fill(archive):
        # 冻结的监控器包（跳过其中的配置，配置统一由 config/ 提供）。
        for path in monitor.rglob("*"):
            if path.is_file() and path.name not in CONFIG_NAMES:
                archive.write(path, Path("PBB") / path.relative_to(DIST_DIR))
        # 顶层说明文档：Markdown 与其导出的 PDF 一起带出。
        for md_path, pdf_path in PDF_SOURCES:
            archive.write(md_path, "PBB/" + Path(md_path).name)
            archive.write(pdf_path, "PBB/" + Path(pdf_path).name)
        archive.write(f"{DOCS_DIR}/PACKAGING.md", "PBB/PACKAGING.md")
        # 源码与资源：改写到发布包的 source/ 目录下，保持仓库内相对结构。
        for path in source_paths():
            if path.name not in CONFIG_NAMES:
                archive.writestr(str(Path("PBB/source") / path).replace('\\', '/'), source_payload(path))
        # 可编辑配置统一放在外层 config/。
        for name, data in distribution_configs().items():
            archive.writestr('PBB/config/' + name, data)
        for name, data in distribution_charsets().items():
            archive.writestr('PBB/charsets/' + name, data)
        # 发布包根目录的外壳脚本（start_ui/start_cli/rebuild/environment/tune_*）。
        for path in Path('offline').glob('*.bat'):
            archive.write(path, 'PBB/' + path.name)
        # 预编译二进制及其清单：发布版保守指令集，用户可自行 rebuild 覆盖。
        for name in ('pbb_engine.exe', 'pbb_ui_engine.exe', os.path.basename(build._pbb_core_path())):
            for suffix in ('', '.build.json'):
                path = paths.BUILD_DIR / (name + suffix)
                archive.write(path, 'PBB/source/build/' + path.name)

    archive_path = write_zip_atomic(release / "PBB-windows-x64-pure.zip", fill)
    # 记录本次 dist 目录，供 package_offline.py 复用（run_ui.bat 也会读）。
    (paths.BUILD_DIR / "ui_dist.txt").write_text(DIST_DIR, encoding="ascii")
    print("Pure archive:", archive_path.resolve())


if __name__ == "__main__":
    main()
