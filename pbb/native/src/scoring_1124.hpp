// ===== poly_1124: 多项式特征扩展 (预计算表版) =====
// 46 维 → 1123 维 (一阶 46 + 二阶 1077, 排除 4 对)
// 模型权重 1124 维 = bias(1) + 1123 特征
inline void poly_1124(double *xp, const double *x) {
  for (int y = 0; y < 1123; y++) {
    auto& e = POLY_TABLE_1124[y];
    xp[y] = e.is_pair ? x[e.p] * x[e.q] : x[e.p];
  }
}

// ===== 1124 维点积 (bias + 1123 特征), 权重为 float, 累加为 double =====
// SIMD: AVX-512 8 路 / AVX2 4 路 (4 个独立累加器打散依赖链 + FMA), 无 SIMD 时标量回退。
// 注: 向量化改变累加次序 (标量版在 MSVC 下是 1123 级串行依赖链, 极慢), 结果与标量路径
//     存在末位差异; 因编译期常量宏决定, 同一份二进制内仍完全可复现 (线程数无关性不变)。
inline double dot_1124_f(const double *xa, const float *m) {
#if PBB_HAS_AVX512
  __m512d a0 = _mm512_setzero_pd(), a1 = _mm512_setzero_pd();
  __m512d a2 = _mm512_setzero_pd(), a3 = _mm512_setzero_pd();
  int i = 0;
  for (; i + 31 < 1123; i += 32) {
    a0 = _mm512_fmadd_pd(_mm512_loadu_pd(xa + i),
                         _mm512_cvtps_pd(_mm256_loadu_ps(m + i + 1)), a0);
    a1 = _mm512_fmadd_pd(_mm512_loadu_pd(xa + i + 8),
                         _mm512_cvtps_pd(_mm256_loadu_ps(m + i + 9)), a1);
    a2 = _mm512_fmadd_pd(_mm512_loadu_pd(xa + i + 16),
                         _mm512_cvtps_pd(_mm256_loadu_ps(m + i + 17)), a2);
    a3 = _mm512_fmadd_pd(_mm512_loadu_pd(xa + i + 24),
                         _mm512_cvtps_pd(_mm256_loadu_ps(m + i + 25)), a3);
  }
  for (; i + 7 < 1123; i += 8)
    a0 = _mm512_fmadd_pd(_mm512_loadu_pd(xa + i),
                         _mm512_cvtps_pd(_mm256_loadu_ps(m + i + 1)), a0);
  __m512d acc = _mm512_add_pd(_mm512_add_pd(a0, a1), _mm512_add_pd(a2, a3));
  double s = m[0] + _mm512_reduce_add_pd(acc);
  for (; i < 1123; i++) s += xa[i] * m[i + 1];
  return s;
#elif PBB_HAS_AVX2
  __m256d a0 = _mm256_setzero_pd(), a1 = _mm256_setzero_pd();
  __m256d a2 = _mm256_setzero_pd(), a3 = _mm256_setzero_pd();
  int i = 0;
  for (; i + 15 < 1123; i += 16) {
    a0 = _mm256_fmadd_pd(_mm256_loadu_pd(xa + i),
                         _mm256_cvtps_pd(_mm_loadu_ps(m + i + 1)), a0);
    a1 = _mm256_fmadd_pd(_mm256_loadu_pd(xa + i + 4),
                         _mm256_cvtps_pd(_mm_loadu_ps(m + i + 5)), a1);
    a2 = _mm256_fmadd_pd(_mm256_loadu_pd(xa + i + 8),
                         _mm256_cvtps_pd(_mm_loadu_ps(m + i + 9)), a2);
    a3 = _mm256_fmadd_pd(_mm256_loadu_pd(xa + i + 12),
                         _mm256_cvtps_pd(_mm_loadu_ps(m + i + 13)), a3);
  }
  for (; i + 3 < 1123; i += 4)
    a0 = _mm256_fmadd_pd(_mm256_loadu_pd(xa + i),
                         _mm256_cvtps_pd(_mm_loadu_ps(m + i + 1)), a0);
  __m256d acc = _mm256_add_pd(_mm256_add_pd(a0, a1), _mm256_add_pd(a2, a3));
  __m128d h = _mm_add_pd(_mm256_castpd256_pd128(acc), _mm256_extractf128_pd(acc, 1));
  double s = m[0] + (_mm_cvtsd_f64(h) + _mm_cvtsd_f64(_mm_unpackhi_pd(h, h)));
  for (; i < 1123; i++) s += xa[i] * m[i + 1];
  return s;
#else
  double s = m[0];
  for (int i = 0; i < 1123; i++) s += xa[i] * m[i + 1];
  return s;
#endif
}

// ===== 46 维点积 (共享二级门 / 每族一阶预筛共用), SIMD 8/4 路 + 标量回退 =====
// w/x 均为 46 个 double; 权重为编译期常量表, xp 常驻 L1, 故直接全量向量化。
static inline double dot46(const double *w, const double *x) {
#if PBB_HAS_AVX512
  __m512d a0 = _mm512_setzero_pd(), a1 = _mm512_setzero_pd();
  a0 = _mm512_fmadd_pd(_mm512_loadu_pd(w),      _mm512_loadu_pd(x),      a0);
  a1 = _mm512_fmadd_pd(_mm512_loadu_pd(w + 8),  _mm512_loadu_pd(x + 8),  a1);
  a0 = _mm512_fmadd_pd(_mm512_loadu_pd(w + 16), _mm512_loadu_pd(x + 16), a0);
  a1 = _mm512_fmadd_pd(_mm512_loadu_pd(w + 24), _mm512_loadu_pd(x + 24), a1);
  a0 = _mm512_fmadd_pd(_mm512_loadu_pd(w + 32), _mm512_loadu_pd(x + 32), a0);
  double s = _mm512_reduce_add_pd(_mm512_add_pd(a0, a1));
  for (int i = 40; i < 46; i++) s += w[i] * x[i];
  return s;
#elif PBB_HAS_AVX2
  __m256d a0 = _mm256_setzero_pd(), a1 = _mm256_setzero_pd();
  for (int i = 0; i + 7 < 40; i += 8) {  // 0..39 每轮 8 元, 尾部 40..45 标量
    a0 = _mm256_fmadd_pd(_mm256_loadu_pd(w + i),     _mm256_loadu_pd(x + i),     a0);
    a1 = _mm256_fmadd_pd(_mm256_loadu_pd(w + i + 4), _mm256_loadu_pd(x + i + 4), a1);
  }
  __m256d acc = _mm256_add_pd(a0, a1);
  __m128d h = _mm_add_pd(_mm256_castpd256_pd128(acc), _mm256_extractf128_pd(acc, 1));
  double s = _mm_cvtsd_f64(h) + _mm_cvtsd_f64(_mm_unpackhi_pd(h, h));
  for (int i = 40; i < 46; i++) s += w[i] * x[i];
  return s;
#else
  double s = 0.0;
  for (int i = 0; i < 46; i++) s += w[i] * x[i];
  return s;
#endif
}

// ===== 由 x1(SP1 语义, 护盾折点 70) 构造 SP2 语义 x2[0..42] (护盾折点 60) =====
// 对齐 scoring_sp1.hpp::get_43_sp2: 技能衰减用 skill_para[25] 表, 31/32 封顶 64 且 kill 系数 0.8。
// 前置: n.skill[]/n.freq[] 已由 calc_skills 填好; 调用必须在 shadow 号加载前。
inline void build_x2(const Name &n, const double *x1, double *x2) {
  for (int i = 0; i < 46; i++) x2[i] = 0.0;
  for (int i = 0; i < 8; i++) x2[i] = x1[i];  // 属性/HP 部分与 x1 相同
  static const double skill_para[25] = {
    1, 1, 1, 0.5, 0.75, 0.75, 1, 1, 0.75, 0.5, 1, 1, 1, 0.75, 1, 0.75,
    0.2, 1, 0.75, 0.5, 0.3, 0.75, 0.75, 0.3, 0.75
  };
  double zd = 1.0, kill = 1.0;
  for (int k = 0; k < 16; k++) {
    int sk = n.skill[k];
    double f = n.freq[k];
    if (f == 0) continue;
    if (sk < 25) {
      x2[sk + 8] = zd * f;
      zd *= (1.0 - f * skill_para[sk] / 128.0);
    } else if (sk == 31 || sk == 32) {
      if (f >= 64.0) f = 64.0;
      x2[sk + 8] = kill * f;
      kill *= (1.0 - f * 0.8 / 128.0);
    } else {
      x2[sk + 8] = f;  // 被动技能: 不衰减
    }
  }
  if (x2[37] <= 60.0) x2[37] = x2[37] * x2[37] / 60.0;
  else x2[37] = x2[37] * 2.0 - 60.0;
}

// ===== sp_eval_plan: 按 ScorePlan 逐族评分 (支持跳过 + any 短路) =====
// fam_mask: 允许评选的族位掩码 (由 fam_pass_mask 产出, 已含 pl.comp 筛选);
//   位 m 为 0 的族直接跳过 (不过该族一阶预筛), 未算族 result.sc[m] 保持调用方初值 (约定先清零)。
// a1 = poly_1124(xp_x) 仅在需要 SP1 族时懒算; a2 = poly_1124(x2) 仅在需要 SP2 族时懒算。
// any_mode: 按 pl.order 顺序逐族评分, 首次 (minv[m]>0 且 sc[m]>=minv[m]) 即停止后续族。
// 各族计算口径与旧 sp_eval_extra 逐字一致 (qp/qd 为 float 逐次累加 + 截断)。
// 中文补充 (各族门控与量纲):
//   * qp/qd 用 xp_x 语义 (SP1, 护盾折点 70), 其余 8 族里 pp/pd/cqd 也用 xp_x;
//     cp/fp/wc/fs/pj 用 x2 语义 (SP2, 护盾折点 60)。
//   * 各族还有一个"前置条件"判据 (如 cqd 要求 xp_x[32]>=30, fp/wc 要求 x2[29]<=35,
//     fs 要求 x2[31]*2+x2[32]+... >= 50): 不满足时该族直接记 0 分, 不展开点积。
//   * cqd 是唯一的"双模型取大"族 (MODEL_CQD0 与 MODEL_CQD3), 得到后还要 ×100 再取整。
//   * C() 负责"负数夹到 0 后四舍五入"; qp/qd 例外地用 (int) 直接截断 —— 这是历史口径, 不要统一。
//   * 短路判定只看 minv (普通阈值), 不看 ptt: any 模式可能在 ptt 还能救回该名时就提前停了,
//     这是"any 会改变输出语义"的根源 (engine.hpp 有对应说明)。
inline void sp_eval_plan(const ScorePlan &pl, const double *xp_x, const double *x2,
                         unsigned fam_mask, ScoreResult &result) {
  double a1[1123], a2[1123];
  bool have1 = false, have2 = false;
  auto get1 = [&]() -> const double* { if (!have1) { poly_1124(a1, xp_x); have1 = true; } return a1; };
  auto get2 = [&]() -> const double* { if (!have2) { poly_1124(a2, x2);   have2 = true; } return a2; };
  auto C = [](double v) { return (int)std::round(v > 0 ? v : 0.0); };
  int *sc = result.sc;
  for (int oi = 0; oi < pl.norder; oi++) {
    const int m = pl.order[oi];
    if (!((fam_mask >> m) & 1u)) continue;   // 未过族一阶预筛 (或未列入计划) 的族不展开
    switch (m) {
      case M_QP: {
        const double* a = get1();
        float s = MODEL_QP0[0];
        for (int i = 0; i < 1123; ++i) s += a[i] * MODEL_QP0[i + 1];
        result.qp_reference_qp = (int)s; // 保留原模型整数分，供离线对照。
        const double u = xp_x[32];
        const double strength = u > 0.0 ? xp_x[43] * 100.0 / u : 0.0;
        result.qp_deduction = qp_shadow_deduction(u, strength);
        // 先保留原QP截断口径，再减浮点扣分并截断；不新增负分夹取规则。
        sc[m] = (int)(result.qp_reference_qp - result.qp_deduction);
        break;
      }
      case M_QD: {
        const float *W = MODEL_QD0;
        const double *a = get1();
        float s = W[0];
        for (int i = 0; i < 1123; i++) s += a[i] * W[i + 1];
        sc[m] = (int)s;
        break;
      }
      case M_PP: sc[m] = result.qp_reference_pp = C(dot_1124_f(get1(), MODEL_PP0)); break;
      case M_PD: sc[m] = C(dot_1124_f(get1(), MODEL_PD0)); break;
      case M_CQD: {
        const double *a = get1();
        double c2 = dot_1124_f(a, MODEL_CQD0);
        double c1 = (xp_x[32] >= 30.0) ? dot_1124_f(a, MODEL_CQD3) : 0.0;
        double scq = (c1 > c2) ? c1 : c2; if (scq < 0) scq = 0; scq *= 100.0;
        sc[m] = (int)std::round(scq);
        break;
      }
      case M_CP: {
        const double *a = get2();
        sc[m] = C((x2[29] >= 25.0) ? dot_1124_f(a, MODEL_CP0) : 0.0);
        break;
      }
      case M_FP: {
        const double *a = get2();
        sc[m] = C((x2[29] <= 35.0) ? dot_1124_f(a, MODEL_FP0) : 0.0);
        break;
      }
      case M_WC: {
        const double *a = get2();
        sc[m] = C((x2[29] <= 35.0) ? dot_1124_f(a, MODEL_WC0) : 0.0);
        break;
      }
      case M_FS: {
        const double *a = get2();
        double v = (x2[31]*2.0 + x2[32] + 0.01*x2[31]*x2[19] + 0.01*x2[31]*x2[36] >= 50.0)
                   ? dot_1124_f(a, MODEL_FS0) : 0.0;
        sc[m] = C(v);
        break;
      }
      case M_PJ: sc[m] = C(dot_1124_f(get2(), MODEL_PJ0)); break;
      default: break;
    }
    if (pl.any_mode && score_normal_pass(pl, result, m)) break;
  }
}

// ===== ptt (potential): 单个 name base 字节置 63 后可达到的最大评分 =====
// 对齐 SP2.cpp 主流程 (L405-503): 组队加成仅考虑「一个 name base 变化」的上限,
// 候选 = HP 1 + 7 属性 + 18 技能组; HP/属性候选需原始 pass, 技能候选逐个重判 pass。
// 与 SP2 的差异: 用 poly_1124+dot_1124_f 精确重算候选评分 (SP2 用泰勒近似)。
inline const float* ptt_model_of(int m) {
  switch (m) {
    case M_CP: return MODEL_CP0;
    case M_FP: return MODEL_FP0;
    case M_WC: return MODEL_WC0;
    case M_FS: return MODEL_FS0;
    case M_PJ: return MODEL_PJ0;
    default: return nullptr;
  }
}

// 各族 pass 判据 (与 sp_eval_plan 中各族门控一致)
inline bool ptt_pass(int m, const double* x) {
  switch (m) {
    case M_CP: return x[29] >= 25.0;
    case M_FP: case M_WC: return x[29] <= 35.0;
    case M_FS: return (x[31]*2.0 + x[32] + 0.01*x[31]*x[19] + 0.01*x[31]*x[36]) >= 50.0;
    case M_PJ: return true;
    default: return false;
  }
}

// 复刻 SP2 load_name 中 last/freq14/freq15 的推导 (依赖原始 name_base, 与候选人无关)
inline void ptt_fixed_of(const u8_t* nb, const u8_t* skill,
                         int& last, bool& freq14, bool& freq15) {
  last = -1; freq14 = false; freq15 = false;
  const u8_t* a = nb + K;
  for (int i = 0, j = 0; i < K; i += 4, j++) {
    u8_t p = std::min({a[i], a[i + 1], a[i + 2], a[i + 3]});
    if (p > 10 && skill[j] < 35) {
      if (skill[j] < 25) last = j;
      if (i == 56) freq14 = true;
      if (i == 60) freq15 = true;
    }
  }
}

// 复刻 SP2 get_43: 由 name_base/skill/last/freq14/freq15/shadowi2 构造 SP2 语义 x[0..45]
// 中文补充 (与 build_x2 的关系): 本函数是"从原始 name_base 重新构造"的版本, 供 ptt 在
//   篡改过某个字节后重算评分; build_x2 则是"从已算好的 x1 派生"的快速版本, 供正常评分。
//   两者的语义 (护盾折点 60/70、衰减系数、守护迁移、隐匿标志) 必须严格对齐 SP2 参考实现。
// 注意 x 数组被写成 50 项 (前 46 项有效), 因为内部临时变量布局沿用历史实现。
inline void get43_from_base(const u8_t* nb, const u8_t* skill,
                            int last, bool freq14, bool freq15,
                            double shadowi2, double* x) {
  for (int i = 0; i < 50; i++) x[i] = 0.0;
  u8_t bh[10];
  for (int i = 0; i < 10; i++) bh[i] = nb[i];
  sort10(bh);
  x[0] = 154 + bh[3] + bh[4] + bh[5] + bh[6];
  x[1] = 36 + median(nb[10], nb[11], nb[12]);
  x[2] = 36 + median(nb[13], nb[14], nb[15]);
  x[3] = 36 + median(nb[16], nb[17], nb[18]);
  x[4] = 36 + median(nb[19], nb[20], nb[21]);
  x[5] = 36 + median(nb[22], nb[23], nb[24]);
  x[6] = 36 + median(nb[25], nb[26], nb[27]);
  x[7] = 36 + median(nb[28], nb[29], nb[30]);
  const u8_t* a = nb + K;
  u8_t fq[16];
  for (int i = 0, j = 0; i < K; i += 4, j++) {
    u8_t p = std::min({a[i], a[i + 1], a[i + 2], a[i + 3]});
    if (p > 10 && skill[j] < 35) fq[j] = p - 10; else fq[j] = 0;
  }
  if (last != -1) fq[last] <<= 1;
  if (freq14 && last != 14) fq[14] += std::min({nb[60], nb[61], fq[14]});
  if (freq15 && last != 15) fq[15] += std::min({nb[62], nb[63], fq[15]});
  double zd = 1.0, kill = 1.0;
  static const double skill_para[25] = {
    1, 1, 1, 0.5, 0.75, 0.75, 1, 1, 0.75, 0.5, 1, 1, 1, 0.75, 1, 0.75,
    0.2, 1, 0.75, 0.5, 0.3, 0.75, 0.75, 0.3, 0.75
  };
  for (int k = 0; k < 16; k++) {
    int sk = skill[k];
    if (sk < 25) {
      x[sk + 8] = zd * fq[k];
      zd *= (1.0 - fq[k] * skill_para[sk] / 128.0);
    } else if (sk == 31 || sk == 32) {
      if (fq[k] >= 64) fq[k] = 64;
      x[sk + 8] = kill * fq[k];
      kill *= (1.0 - fq[k] * 0.8 / 128.0);
    } else {
      x[sk + 8] = fq[k];
    }
  }
  if (x[37] <= 60.0) x[37] = x[37] * x[37] / 60.0;
  else x[37] = x[37] * 2.0 - 60.0;
  x[43] = (x[32] > 0.0) ? shadowi2 * x[32] / 100.0 : 0.0;
  if (x[42] > 0.0) x[44] = 1.0;
  if (x[37] > 0.0) { x[45] = x[26]; x[26] = 0.0; }
}

// shadowi2 (SP2 语义暗影加权): 依赖已加载暗影号的 name_base[3..30]
inline double shadowi2_of(const Name& n) {
  int p0 = median(n.name_base[10], n.name_base[11], n.name_base[12]);
  int p1 = median(n.name_base[13], n.name_base[14], n.name_base[15]);
  int p2 = median(n.name_base[16], n.name_base[17], n.name_base[18]);
  int p3 = median(n.name_base[19], n.name_base[20], n.name_base[21]);
  int p4 = median(n.name_base[22], n.name_base[23], n.name_base[24]);
  int p5 = median(n.name_base[25], n.name_base[26], n.name_base[27]);
  int p6 = median(n.name_base[28], n.name_base[29], n.name_base[30]);
  int p7 = 154 + n.name_base[3] + n.name_base[4] + n.name_base[5] + n.name_base[6];
  return p0*2.2 + p1*0.75 + p2*1.9 + p3*1.3 + p4*0.6 + p5*1.2 - p6*1.8 + p7*1.0;
}

// 计算族 m 在「单个 name base 字节置 63」下的最大评分 (含基线; <=0 时返回 0)
// 中文补充 (为什么要有这个函数): 潜力筛的语义是「如果某个 name base 字节取到理论最大值 63,
//   这个号能不能达到候选阈值」。所以要在候选集合 (HP 1 + 7 属性 + 18 技能组 = 26 个候选)
//   上逐个重算评分取最大值, 而不是用梯度近似 —— 代价高, 因此只在「普通阈值全没过」时才调用。
// 候选构造细节: HP 与属性候选只在 ptt_pass(m,x) 成立时才评估 (门控不成立时分数再高也不算过),
//   技能候选则必须先把改动后的 name_base 重新过一遍 ptt_pass 才能计分。
// 返回值与 SP2 一致: 不夹取负值 (调用方阈值恒 >0, 负值在语义上等同于"不可能达标")。
inline int ptt_score_max(int m, const u8_t* nb, const u8_t* skill,
                         int last, bool freq14, bool freq15, double shadowi2) {
  const float* W = ptt_model_of(m);
  if (!W) return 0;
  double x[50];
  get43_from_base(nb, skill, last, freq14, freq15, shadowi2, x);
  double xa[1123], xc[50];
  poly_1124(xa, x);
  double best = dot_1124_f(xa, W);  // 基线 (SP2 score_max 初值 = score_init)
  if (ptt_pass(m, x)) {
    // HP 候选: 原始 nb[7..9] 中的最小值位置置 63 (SP2 用未排序 name_base)
    for (int i = 0; i < 50; i++) xc[i] = x[i];
    int j = 7;
    if (nb[8] < nb[j]) j = 8;
    if (nb[9] < nb[j]) j = 9;
    u8_t bh[10];
    for (int i = 0; i < 10; i++) bh[i] = nb[i];
    bh[j] = 63; sort10(bh);
    xc[0] = 154 + bh[3] + bh[4] + bh[5] + bh[6];
    poly_1124(xa, xc);
    double s = dot_1124_f(xa, W);
    if (s > best) best = s;
    // 7 属性候选: 组内最大值位置 → 36 + max (SP2 恒算, 不跳过)
    for (int t = 1; t < 8; t++) {
      for (int i = 0; i < 50; i++) xc[i] = x[i];
      int idx = 7 + t * 3;
      int mx = nb[idx];
      if (nb[idx + 1] > mx) mx = nb[idx + 1];
      if (nb[idx + 2] > mx) mx = nb[idx + 2];
      xc[t] = 36 + mx;
      poly_1124(xa, xc);
      s = dot_1124_f(xa, W);
      if (s > best) best = s;
    }
  }
  // 18 技能候选: 组内最小值位置置 63 → 重算 pass 后才计分
  u8_t nb2[M];
  for (int i = -2; i < 16; i++) {
    int j;
    if (i < 0) {
      j = (nb[64 + i * 2] < nb[65 + i * 2]) ? (64 + i * 2) : (65 + i * 2);
    } else {
      j = 64 + i * 4;
      if (nb[65 + i * 4] < nb[j]) j = 65 + i * 4;
      if (nb[66 + i * 4] < nb[j]) j = 66 + i * 4;
      if (nb[67 + i * 4] < nb[j]) j = 67 + i * 4;
    }
    if (nb[j] >= 63) continue;  // 置 63 无变化
    memcpy(nb2, nb, M);
    nb2[j] = 63;
    get43_from_base(nb2, skill, last, freq14, freq15, shadowi2, xc);
    if (ptt_pass(m, xc)) {
      poly_1124(xa, xc);
      double s = dot_1124_f(xa, W);
      if (s > best) best = s;
    }
  }
  return (int)std::round(best);  // 与 SP2 一致: 不夹取负值 (门控阈值恒 >0, 等价)
}

