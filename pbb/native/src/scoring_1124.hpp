// (R ∨ S ∨ T) 且非 FREE 给 PRE(1, 待过二级 G3); 否则淘汰(0)。
// F 平面 (FREE): 431*x0 + 813*P1 + 807*P2 + 1000*P3 + 989*P4 + 812*P5 + 966*P6 + 924*P7 >= 451667
// R 平面 (PRE ): 372*x0 + 326*P1 + 791*P2 + 1000*P3 + 542*P4 + 562*P5 + 906*P6 + 928*P7 >= 331652
// S 平面 (PRE ): 215*x0 +  44*P1 + 486*P2 +  815*P3 +  74*P4 +  86*P5 + 563*P6 + 1000*P7 >= 204325
// T 平面 (PRE ):  51*x0 +  54*P1 + 372*P2 +  750*P3 - 282*P4 +  42*P5 +  12*P6 + 1000*P7 >= 125128
// 系数为 Pareto 拟合方向 ×1000 取整; 阈值取两队 (各 1e7 负样本) 分位数均值后统一。
