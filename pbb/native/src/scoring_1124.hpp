// 该族平面1 的有效门限: 各族常量 t1 (与阈值 K 无关), 仅供 flat 调用点/工具统一入口。
static inline double fam_t1_of(int m, int K) {
  (void)K;
  return FAM_GATE[m].t1;
}

// 单族预筛: xp[0..45] 为 score_full Step 5 之后的最终 xp_x。单平面或双平面 OR, 门限用各族常量 t1/t2。
static inline bool fam_gate_ok(int m, const double* xp, int K) {
  (void)K;
  const FamGate& g = FAM_GATE[m];
  if (dot46(g.w1, xp) >= g.t1) return true;
  if (g.w2 && dot46(g.w2, xp) >= g.t2) return true;
  return false;
}

// 允许评选的族位掩码: 无论 PRE/FREE, 每族都须过其自身的一阶预筛才展开。
static inline unsigned fam_pass_mask(const ScorePlan& pl, const double* xp) {
  unsigned mk = 0;
  for (int m = 0; m < M_N; m++) {
    if (!pl.comp[m]) continue;
    if (fam_gate_ok(m, xp, pl.minv[m])) mk |= 1u << m;
  }
  return mk;
}

// ---- 29-CE 无分支排序网络 (升序, 结果与 sort10() 逐值相同) ----
// 中文说明: 与 utils.hpp::sort10 功能完全等价 (29 次比较交换, 升序), 写成"网络"形式是为了
//   让编译器直接展开成 cmp/cmov 序列而不产生分支; 两处实现必须保持逐值一致 ——
//   自动测试会把 sort10 与 sort10_net 的结果对拍 (HP 由排序后 b[3..6] 决定, 不一致就会漏号)。
// 只排前 10 项: name_base[10..30] 是属性语义位, 排序它们会破坏 median 的含义。
static inline void sort10_net(u8_t* b)
{
#define CEN(i, j) do { u8_t x_ = b[i], y_ = b[j]; b[i] = x_ < y_ ? x_ : y_; b[j] = x_ < y_ ? y_ : x_; } while (0)
	CEN(0,5); CEN(1,6); CEN(2,7); CEN(3,8); CEN(4,9);
	CEN(0,3); CEN(1,4); CEN(5,8); CEN(6,9);
	CEN(0,2); CEN(3,6); CEN(7,9);
	CEN(0,1); CEN(2,4); CEN(5,7); CEN(8,9);
	CEN(1,2); CEN(3,5); CEN(4,6); CEN(7,8);
	CEN(1,3); CEN(2,5); CEN(4,7); CEN(6,8);
	CEN(2,3); CEN(6,7);
	CEN(3,4); CEN(5,6);
	CEN(4,5);
#undef CEN
}

static inline int gate_level_of(const u8_t* nb, int* P) {
  // 中文补充 (本函数是最热的筛子, 约 99.99% 的候选死在这里):
  //   * 输入 nb = name_base (只读)。额外副作用: 把 P1..P7 写回调用方数组, 下标映射为
  //     P[0]=P1, P[1]=P2, ..., P[6]=P7 (即 P[i] 存 P(i+1)) —— 与 ScoreResult.props 的前 7 项
  //     以及门控平面的取值顺序一致, 上层因此不必重算 median。
  //     返回 0/1/2 = 淘汰 / PRE 待定 (需过共享二级门) / FREE 直过 (免检)。
  //   * 早退只省计算, 不改判定: 免费维 (无需排序的 median) 先算, 用「剩余维取最大值」的上界
  //     判断四张平面是否必然全部不达标, 命中就直接返回 0, 连后 3 个中位数和排序都省掉。
  //   * 返回 >0 时保证 P[0..6] 全部已填; 返回 0 时 P[0]/P[3]/P[4] 可能未填, 调用方不得使用。
  //   * P7 < 27 的提前淘汰是生产标定 (该档最多携带 0.5% 加权价值), 属于门控策略的一部分。
  // ---- 第 1+2 级 (对应旧门控 V<24 / V<165 两档): P7, 再 +P2+P3+P6 ----
  const int P7 = P[6] = median(nb[28], nb[29], nb[30]);
  // Production calibration: P7 <= 26 carries at most 0.5% weighted value
  // after the per-family t1 gates below. Reject it before computing P2..P6.
  if (P7 < 27) return 0;
  const int P2 = P[1] = median(nb[13], nb[14], nb[15]);
  const int P3 = P[2] = median(nb[16], nb[17], nb[18]);
  const int P6 = P[5] = median(nb[25], nb[26], nb[27]);
  // 四平面在已算免费维上的部分和
  int Fa = GATE_F_W7 * P7 + GATE_F_W2 * P2 + GATE_F_W3 * P3 + GATE_F_W6 * P6;
  int Ra = GATE_R_W7 * P7 + GATE_R_W2 * P2 + GATE_R_W3 * P3 + GATE_R_W6 * P6;
  int Sa = GATE_S_W7 * P7 + GATE_S_W2 * P2 + GATE_S_W3 * P3 + GATE_S_W6 * P6;
  int Ta = GATE_T_W7 * P7 + GATE_T_W2 * P2 + GATE_T_W3 * P3 + GATE_T_W6 * P6;
  // ① 免费淘汰: 四平面把剩余维 (P1/P4/P5/x0) 全取最大仍 <θ ⇒ 中位数/排序都省了
  if (Fa + GATE_F_REM2 < GATE_F_TH && Ra + GATE_R_REM2 < GATE_R_TH &&
      Sa + GATE_S_REM2 < GATE_S_TH && Ta + GATE_T_REM2 < GATE_T_TH) return 0;

  // ---- 第 3 级 (对应旧门控 V<250 那一档): +P1+P4+P5 ----
  const int P1 = P[0] = median(nb[10], nb[11], nb[12]);
  const int P4 = P[3] = median(nb[19], nb[20], nb[21]);
  const int P5 = P[4] = median(nb[22], nb[23], nb[24]);
  const int Fb = Fa + GATE_F_W1 * P1 + GATE_F_W4 * P4 + GATE_F_W5 * P5;
  const int Rb = Ra + GATE_R_W1 * P1 + GATE_R_W4 * P4 + GATE_R_W5 * P5;
  const int Sb = Sa + GATE_S_W1 * P1 + GATE_S_W4 * P4 + GATE_S_W5 * P5;
  const int Tb = Ta + GATE_T_W1 * P1 + GATE_T_W4 * P4 + GATE_T_W5 * P5;
  // ② 免费淘汰: 四平面只剩付费维 x0, 取最大 406 仍 <θ ⇒ 排序网络也可省掉
  if (Fb + GATE_F_REM3 < GATE_F_TH && Rb + GATE_R_REM3 < GATE_R_TH &&
      Sb + GATE_S_REM3 < GATE_S_TH && Tb + GATE_T_REM3 < GATE_T_TH) return 0;

  // ---- 第 4 级 (对应旧门控 sort10): 必须知道 x0 ----
  u8_t b[10];
  for (int i = 0; i < 10; i++) b[i] = nb[i];
  sort10_net(b);
  const int x0 = 154 + b[3] + b[4] + b[5] + b[6];
  if (Fb + GATE_F_W0 * x0 >= GATE_F_TH) return 2;   // FREE 直过
  if (Rb + GATE_R_W0 * x0 >= GATE_R_TH) return 1;   // PRE 待定 (需过二级 G3)
  if (Sb + GATE_S_W0 * x0 >= GATE_S_TH) return 1;   // PRE 待定 (困难族救援平面)
  if (Tb + GATE_T_W0 * x0 >= GATE_T_TH) return 1;   // PRE 待定 (困难族救援平面)
  return 0;
}

// ===== score_full: 完整评分流水线 (SQP/SQD) =====
// 不做 V 值检查, 对所有名字直接评分。
// plan: 评分计划 (nullptr ⇒ plan_default(), 即全 10 族)。
// 返回值: ScoreResult, flag 始终为 true
// 中文注意: 文档里"flag 始终为 true"只描述旧版; 现版本 flag 是「是否过初筛/二级门」的存活位,
//   为 false 时 sc[]/props[] 一律不可用 (调用方拿到后先判 flag)。
// 流水线步骤 (与代码内 Step 编号一致, 顺序不可交换):
//   Step 1 load_name      — KSA + 属性过滤 + V (可能三级早退)
//   Step 2 Q 门控         — 只依赖 name_base, 死则立即返回; 顺带填 prop[0..6]
//   Step 2b HP            — V<250 时补一次 sort10 (早退路径没排过序), 否则 HP 会算错
//   Step 3 calc_skills    — 覆盖 name_base 技能区, 属性区保留
//   Step 3b ptt 快照      — 保存原始 name_base + last/freq14/freq15 (后续步骤会改动它们)
//   Step 4 xp_x / Step 4b x2 — 46 维特征 (x2 必须在暗影号覆盖之前构造)
//   Step 5 暗影/隐匿/守护 — 三个衍生维 xp43/xp44/xp45
//   Step 5b 二级门 + 每族预筛 — 必须在 Step 5 之后 (判据含衍生维)
//   Step 6 逐族打分       — 懒算 poly_1124, 支持 any 短路
//   Step 7 ptt            — 仅当无任何 comp 族普通达标时才计算潜力上限
inline ScoreResult score_full(const char* name, int name_len, Name& name_obj,
                              const ScorePlan* plan = nullptr) {
  const ScorePlan& pl = plan ? *plan : plan_default();
  ScoreResult result = {};
  memset(&result, 0, sizeof(result));

  // ---- Step 1: 加载名字, 提取属性 ----
  name_obj.load_name(name, name_len);

  // ---- Step 2: Q 门控 (新门控, 只依赖 name_base) ----
  // 门控内部按旧门控三级早退顺序算 median 并写入 prop[0..6] (=P1..P7);
  // 被判死(0 档)时 prop[0],prop[3],prop[4] 未填, 但此处立即返回, 不会使用。
  int prop[8];
  const int lvl = gate_level_of(name_obj.name_base, prop);
  if (lvl == 0) {
    result.flag = false;
    return result;
  }
  // HP (sort10 后 name_base[3..6]) 只在放行后才需要。
  // 注意: finish_load_name() 在 V<250 时提前 return, 未做 sort10; 旧门控 V>=380 时该分支
  // 不可达, 但新门控会放行 V<250 的名字, 必须先补排序, 否则 prop[7] 取的是未排序值, HP 算错。
  if (name_obj.V < 250) sort10_net(name_obj.name_base);
  prop[7] = 154 + name_obj.name_base[3] + name_obj.name_base[4]
                + name_obj.name_base[5] + name_obj.name_base[6];

  int V = name_obj.V;

  // ---- Step 3: 技能分布 ----
  name_obj.calc_skills(name);
  for (int k = 0; k < 16; ++k) {
    result.skills[k] = name_obj.skill[k];
    result.freqs[k] = name_obj.freq[k];
    if (name_obj.skill[k] == 24) result.illusion_freq = name_obj.freq[k];
  }

  // ---- Step 3b: ptt 预处理 (仅当计划含启用 ptt 的族) ----
  // calc_skills 刚以 simd_skill_filter 从头重写 name_base[0..127] 为原始序列,
  // 此处保存 ptt 用的原始 name_base 及 last/freq14/freq15 (后续 shadow/还原会改动)。
  bool ptt_any = false;
  for (int m = 0; m < M_N; m++) if (pl.comp[m] && pl.pttv[m] > 0) { ptt_any = true; break; }
  u8_t ptt_nb[M];
  int ptt_last = -1; bool ptt_f14 = false, ptt_f15 = false;
  if (ptt_any) {
    memcpy(ptt_nb, name_obj.name_base, M);
    ptt_fixed_of(ptt_nb, name_obj.skill, ptt_last, ptt_f14, ptt_f15);
  }

  // ---- Step 4: 构建 46 维特征向量 xp_x ----
  double xp_x[46] = {};

  // 属性标准化
  for (int j = 0; j < 7; j++) {
    prop[j] += 36;
    result.props[j] = prop[j];
    xp_x[j + 1] = prop[j];
  }
  xp_x[0] = prop[7];  // HP
  result.props[7] = prop[7];

  // 技能频次: 衰减叠加 (zd/kill 系数)
  for (int i = 0; i < 35; i++) xp_x[i + 8] = 0;

  double zd = 1.0, kill = 1.0;
  for (int k = 0; k < 16; k++) {
    int sk = name_obj.skill[k];
    double f = name_obj.freq[k];
    if (f == 0) continue;

    if (sk == 9 || sk == 16) {        // 生命之轮(9)/苏生术(16)
      xp_x[sk + 8] = zd * f;
      zd *= (1.0 - f * 0.30 / 128.0);
    } else if (sk == 18) {            // 铁壁(18)
      xp_x[sk + 8] = zd * f;
      zd *= (1.0 - f * 0.35 / 128.0);
    } else if (sk == 19 || sk == 23) { // 蓄力(19)/分身(23)
      xp_x[sk + 8] = zd * f;
      zd *= (1.0 - f * 0.60 / 128.0);
    } else if (sk == 20 || sk == 22) { // 聚气(20)/血祭(22)
      xp_x[sk + 8] = zd * f;
      zd *= (1.0 - f * 0.70 / 128.0);
    } else if (sk < 25) {             // 一般主动技能
      xp_x[sk + 8] = zd * f;
      zd *= (1.0 - f * 1.00 / 128.0);
    } else if (sk == 31 || sk == 32) { // 吞噬(31)/召唤亡灵(32)
      xp_x[sk + 8] = kill * f;
      kill *= (1.0 - f * 1.00 / 128.0);
    } else {
      xp_x[sk + 8] = f;               // 被动技能: 不衰减
    }
  }

  // 护盾(xp_x[37], skill ID 29) 非线性变换
  if (xp_x[37] <= 70.0)
    xp_x[37] = xp_x[37] * xp_x[37] / 70.0;
  else
    xp_x[37] = xp_x[37] * 2.0 - 70.0;

  // ---- Step 4b: 构建 SP2 语义向量 x2 (供 cp/fp/wc/fs/pj 族) ----
  // 必须在暗影号加载 (loading_name) 覆盖 skill/freq 之前完成。
  // 若计划中不含任何 SP2 族则整体跳过 (省一次 46 维构造); x2 保持全 0。
  const bool need_sp2 = pl.comp[M_CP] || pl.comp[M_FP] || pl.comp[M_WC]
                     || pl.comp[M_FS] || pl.comp[M_PJ];
  double x2[46] = {};
  if (need_sp2) build_x2(name_obj, xp_x, x2);

  // ---- Step 5: 暗影二段评分 ----
  // ptt_shadowi2: 供 Step 7 ptt 使用 (SP2 语义暗影加权); 未进入暗影分支时为 0。
  double ptt_shadowi2 = 0.0;
  bool ptt_shadow_loaded = false;
  if (xp_x[32] > 0 || x2[32] > 0) {
    char shadow_name[260];
    memcpy(shadow_name, name, name_len);
    shadow_name[name_len] = '?';
    shadow_name[name_len+1] = 's'; shadow_name[name_len+2] = 'h';
    shadow_name[name_len+3] = 'a'; shadow_name[name_len+4] = 'd';
    shadow_name[name_len+5] = 'o'; shadow_name[name_len+6] = 'w';
    shadow_name[name_len+7] = 0;

    name_obj.loading_name(shadow_name);
    int sprop[8];
    sprop[0] = median(name_obj.name_base[10], name_obj.name_base[11], name_obj.name_base[12]);
    sprop[1] = median(name_obj.name_base[13], name_obj.name_base[14], name_obj.name_base[15]);
    sprop[2] = median(name_obj.name_base[16], name_obj.name_base[17], name_obj.name_base[18]);
    sprop[3] = median(name_obj.name_base[19], name_obj.name_base[20], name_obj.name_base[21]);
    sprop[4] = median(name_obj.name_base[22], name_obj.name_base[23], name_obj.name_base[24]);
    sprop[5] = median(name_obj.name_base[25], name_obj.name_base[26], name_obj.name_base[27]);
    sprop[6] = median(name_obj.name_base[28], name_obj.name_base[29], name_obj.name_base[30]);
    sprop[7] = 154 + name_obj.name_base[3] + name_obj.name_base[4]
                   + name_obj.name_base[5] + name_obj.name_base[6];

    double shadowi = sprop[0]*2.8 + sprop[1]*0.6 + sprop[2]*2.5
                   + sprop[3]*1.2 + sprop[4]*1.0 + sprop[5]*1.0
                   - sprop[6]*1.2 + sprop[7]*0.8;
    result.illusion_effective = xp_x[32];
    result.shadow_strength = shadowi;
    double shadowi2 = sprop[0]*2.2 + sprop[1]*0.75 + sprop[2]*1.9
                    + sprop[3]*1.3 + sprop[4]*0.6 + sprop[5]*1.2
                    - sprop[6]*1.8 + sprop[7]*1.0;
    xp_x[43] = (xp_x[32] > 0) ? shadowi * xp_x[32] / 100.0 : 0.0;
    x2[43]   = (x2[32]  > 0) ? shadowi2 * x2[32] / 100.0 : 0.0;
    // SP2 语义暗影加权 (shadowi2_of) 与上式 shadowi2 公式一致, 直接复用。
    ptt_shadowi2 = shadowi2;
    ptt_shadow_loaded = true;
  }

  // 隐匿(xp_x[42], skill ID 34): 标志位, 不 +20
  if (xp_x[42] > 0) xp_x[44] = 1.0;
  if (x2[42] > 0) x2[44] = 1.0;

  // 护盾 > 0: 守护(x[26]) → x[45], 原位清零
  if (xp_x[37] > 0) {
    xp_x[45] = xp_x[26];
    xp_x[26] = 0;
  }
  if (x2[37] > 0) {
    x2[45] = x2[26];
    x2[26] = 0;
  }

  // ---- Step 5b: 二级门 + 每族一阶预筛 ----
  // ① 共享二级门 (PRE 档 lvl==1): 不过则整名判死 (flag=false); FREE 档 lvl==2 直过。
  // ② 无论 PRE/FREE, 再对每族跑其自己的加权平面, 决定是否展开该族完整模型分 (fam_mask)。
  // 两判据都定义在最终 xp_x 上 (含暗影 xp43 / 隐匿 xp44 / 守护 xp45), 故必须在 Step 5 之后求值。
  // 补充: fam_mask 只为 plan.comp 为真的族置位 —— 未列入计划的族永远不会被打分 (sc 保持 0)。
  // 顺序约束 (易错点): 暗影加载会覆盖 name_obj 的 skill/freq/name_base, 因此 x2 必须在
  //   Step 4b 就构造好, 而本步的门控又必须晚于 Step 5 的衍生维赋值 —— 两点缺一不可。
  if (lvl == 1 && !skill_ok_of(xp_x)) {
    result.flag = false;
    return result;
  }
  const unsigned fam_mask = fam_pass_mask(pl, xp_x);

  // ---- Step 6: 按计划逐族评分 (懒算 poly_1124, 支持 any 短路) ----
  // 未列入计划/未过预筛的族 sc[] 保持 0; qp/qd 未算时 result.xp/xd 亦为 0。
  result.sum = V + 36 * 7;
  result.flag = true;
  sp_eval_plan(pl, xp_x, x2, fam_mask, result);
  result.xp = result.sc[M_QP];
  result.xd = result.sc[M_QD];

  // ---- Step 7: ptt (potential) — 单 name base 变化后的评分上限 (仅用于门控) ----
  // 仅当存在启用 ptt 的族, 且无任一 comp 族普通通过时才计算
  // (对齐 SP2: 仅 score<sieve1 时才求 score_max)。
  if (ptt_any) {
    bool any_normal_pass = false;
    for (int m = 0; m < M_N; m++) {
      if (score_normal_pass(pl, result, m)) {
        any_normal_pass = true;
        break;
      }
    }
    if (!any_normal_pass) {
      // 技能候选可能令 x[32] 由 0 变 >0, ptt 需要 SP2 语义 shadowi2; 按需加载暗影号。
      if (!ptt_shadow_loaded) {
        char shadow_name[260];
        memcpy(shadow_name, name, name_len);
        shadow_name[name_len] = '?';
        shadow_name[name_len+1] = 's'; shadow_name[name_len+2] = 'h';
        shadow_name[name_len+3] = 'a'; shadow_name[name_len+4] = 'd';
        shadow_name[name_len+5] = 'o'; shadow_name[name_len+6] = 'w';
        shadow_name[name_len+7] = 0;
        name_obj.loading_name(shadow_name);
        ptt_shadowi2 = shadowi2_of(name_obj);
      }
      for (int m = 0; m < M_N; m++) {
        if (!((fam_mask >> m) & 1u) || pl.pttv[m] <= 0) continue;
        if (pl.minv[m] > 0 && result.sc[m] >= pl.minv[m]) continue;
        result.sc_max[m] = ptt_score_max(m, ptt_nb, name_obj.skill,
                                        ptt_last, ptt_f14, ptt_f15, ptt_shadowi2);
      }
    }
  }

  return result;
}

// ===== score_full_loaded_batch4: 4 路批量评分 (SQP/SQD) =====
// 与 score_full 相同, 但利用已加载的 Name 对象（由 load_name_batch 预处理）。
// plan: 评分计划 (nullptr ⇒ plan_default(), 即全 10 族)。
// 中文补充 (与单路版的差异, 都是"省计算"而非"改语义"):
//   * 先用 gate_level_of 一次性淘汰整批中死掉的 lane, active 位掩码贯穿后续所有步骤:
//     被淘汰的 lane 不参与 calc_skills, 不消耗 PRGA 状态, 也不参与门控/打分 (结果保持全 0)。
//   * 属性区 name_base[0..30] 在 calc_skills_batch4 之前先存进 attr_base 并在之后还原 ——
//     因为技能过滤会整段重写 name_base, 而门控结果与 ptt 快照都需要原始属性值。
//   * 四路之间没有任何共享可变状态 (除各自 Name 对象), 顺序上仍要求"逐 lane"内层循环,
//     以保证每个 lane 的随机数消耗顺序与单独调用单路版一致 (可复现性要求)。
inline void score_full_loaded_batch4(const char* const names[4], int name_len,
                                     Name (&objs)[4], ScoreResult (&results)[4],
                                     const ScorePlan* plan = nullptr) {
  const ScorePlan& pl = plan ? *plan : plan_default();
  memset(results, 0, sizeof results);

  int prop[4][8];
  int lvl[4] = {};
  u8_t attr_base[4][31];
  unsigned active = 0;
  for (int lane = 0; lane < 4; lane++) {
    Name& n = objs[lane];
    memcpy(attr_base[lane], n.name_base, sizeof attr_base[lane]);
    // 门控顺带填 prop[lane][0..6] (=P1..P7), 三级早退决定少算多少 median
    lvl[lane] = gate_level_of(n.name_base, prop[lane]);
    if (lvl[lane] > 0) {
      // HP: 同 score_full, finish_load_name() 在 V<250 时提前 return 未做 sort10
      if (n.V < 250) sort10_net(n.name_base);
      prop[lane][7] = 154 + n.name_base[3] + n.name_base[4] + n.name_base[5] + n.name_base[6];
      active |= 1u << lane;
    }
  }
  if (!active) return;

  Name::calc_skills_batch4(objs, active);
  for (int lane = 0; lane < 4; ++lane) if (active & (1u << lane))
    for (int k = 0; k < 16; ++k)
      if (objs[lane].skill[k] == 24) results[lane].illusion_freq = objs[lane].freq[k];
  // ---- ptt 预处理: 保存原始 name_base + last/freq14/freq15 (必须在 nb[0..30] 还原之前) ----
  bool ptt_any = false;
  for (int m = 0; m < M_N; m++) if (pl.comp[m] && pl.pttv[m] > 0) { ptt_any = true; break; }
  u8_t ptt_nb[4][M];
  int ptt_last[4] = {}; bool ptt_f14[4] = {}, ptt_f15[4] = {};
  if (ptt_any) {
    for (int lane = 0; lane < 4; lane++) if (active & (1u << lane)) {
      memcpy(ptt_nb[lane], objs[lane].name_base, M);
      ptt_fixed_of(ptt_nb[lane], objs[lane].skill,
                   ptt_last[lane], ptt_f14[lane], ptt_f15[lane]);
    }
  }
  for (int lane = 0; lane < 4; lane++)
    if (active & (1u << lane)) memcpy(objs[lane].name_base, attr_base[lane], sizeof attr_base[lane]);

  // ---- 二级技能判据 (只有 PRE 档 level==1 需要; FREE 档 level==2 直过) ----
  // 判据定义在最终 xp_x 上 (含暗影/隐匿/守护维), 故必须等 Step 5 之后求值;
  // 见下方「护盾>0: 守护→x[45]」之后的调用点。

  int sum[4] = {};
  for (int lane = 0; lane < 4; lane++) if (active & (1u << lane)) {
    sum[lane] = objs[lane].V + 36 * 7;
  }

  // 构建 46 维特征向量 (1124 版: 衰减叠加 + 护盾非线性 + 铁壁转移 + 隐匿标志)
  double x[4][46] = {};
  for (int j = 0; j < 7; j++) {
    for (int lane = 0; lane < 4; lane++) if (active & (1u << lane)) {
      prop[lane][j] += 36;
      results[lane].props[j] = prop[lane][j];
      x[lane][j + 1] = prop[lane][j];
    }
  }
  for (int lane = 0; lane < 4; lane++) if (active & (1u << lane)) {
    x[lane][0] = prop[lane][7];
    results[lane].props[7] = prop[lane][7];
  }

  // 技能频次: 衰减叠加 (zd/kill 系数)
  for (int lane = 0; lane < 4; lane++) if (active & (1u << lane)) {
    for (int id = 0; id < 35; id++) x[lane][id + 8] = 0;

    double zd = 1.0, kill = 1.0;
    for (int k = 0; k < 16; k++) {
      int sk = objs[lane].skill[k];
      double f = objs[lane].freq[k];
      if (f == 0) continue;

      if (sk == 9 || sk == 16) {        // 生命之轮(9)/苏生术(16)
        x[lane][sk + 8] = zd * f;
        zd *= (1.0 - f * 0.30 / 128.0);
      } else if (sk == 18) {            // 铁壁(18)
        x[lane][sk + 8] = zd * f;
        zd *= (1.0 - f * 0.35 / 128.0);
      } else if (sk == 19 || sk == 23) { // 蓄力(19)/分身(23)
        x[lane][sk + 8] = zd * f;
        zd *= (1.0 - f * 0.60 / 128.0);
      } else if (sk == 20 || sk == 22) { // 聚气(20)/血祭(22)
        x[lane][sk + 8] = zd * f;
        zd *= (1.0 - f * 0.70 / 128.0);
      } else if (sk < 25) {             // 一般主动技能
        x[lane][sk + 8] = zd * f;
        zd *= (1.0 - f * 1.00 / 128.0);
      } else if (sk == 31 || sk == 32) { // 吞噬(31)/召唤亡灵(32)
        x[lane][sk + 8] = kill * f;
        kill *= (1.0 - f * 1.00 / 128.0);
      } else {
        x[lane][sk + 8] = f;             // 被动技能: 不衰减
      }
      results[lane].skills[k] = sk;
      results[lane].freqs[k] = objs[lane].freq[k];
    }
  }

  // 护盾非线性变换
  for (int lane = 0; lane < 4; lane++) if (active & (1u << lane)) {
    if (x[lane][37] <= 70.0)
      x[lane][37] = x[lane][37] * x[lane][37] / 70.0;
    else
      x[lane][37] = x[lane][37] * 2.0 - 70.0;
  }

  // ---- 二级技能判据 (只有 PRE 档 level==1 需要; FREE 档 level==2 直过) ----
  // 判据定义在最终 xp_x 上 (含暗影/隐匿/守护维), 故必须等 Step 5 之后求值。

  // 构建 SP2 语义向量 x2 (供 cp/fp/wc/fs/pj 族); 必须在暗影号加载前完成
  // 若计划中不含任何 SP2 族则整体跳过, x2 保持全 0
  const bool need_sp2 = pl.comp[M_CP] || pl.comp[M_FP] || pl.comp[M_WC]
                     || pl.comp[M_FS] || pl.comp[M_PJ];
  double x2[4][46] = {};
  if (need_sp2)
    for (int lane = 0; lane < 4; lane++) if (active & (1u << lane))
      build_x2(objs[lane], x[lane], x2[lane]);

  // 暗影二段评分
  double ptt_shadowi2[4] = {};
  bool ptt_shadow_loaded[4] = {};
  for (int lane = 0; lane < 4; lane++) {
    if (!(active & (1u << lane)) || (x[lane][32] <= 0 && x2[lane][32] <= 0)) continue;
    char shadow_name[260];
    memcpy(shadow_name, names[lane], name_len);
    memcpy(shadow_name + name_len, "?shadow", 8);
    objs[lane].loading_name(shadow_name);
    Name& n = objs[lane];
    int sprop[8];
    sprop[0] = median(n.name_base[10], n.name_base[11], n.name_base[12]);
    sprop[1] = median(n.name_base[13], n.name_base[14], n.name_base[15]);
    sprop[2] = median(n.name_base[16], n.name_base[17], n.name_base[18]);
    sprop[3] = median(n.name_base[19], n.name_base[20], n.name_base[21]);
    sprop[4] = median(n.name_base[22], n.name_base[23], n.name_base[24]);
    sprop[5] = median(n.name_base[25], n.name_base[26], n.name_base[27]);
    sprop[6] = median(n.name_base[28], n.name_base[29], n.name_base[30]);
    sprop[7] = 154 + n.name_base[3] + n.name_base[4] + n.name_base[5] + n.name_base[6];
    double shadowi = sprop[0]*2.8 + sprop[1]*0.6 + sprop[2]*2.5
                   + sprop[3]*1.2 + sprop[4]*1.0 + sprop[5]*1.0
                   - sprop[6]*1.2 + sprop[7]*0.8;
    results[lane].illusion_effective = x[lane][32];
    results[lane].shadow_strength = shadowi;
    double shadowi2 = sprop[0]*2.2 + sprop[1]*0.75 + sprop[2]*1.9
                    + sprop[3]*1.3 + sprop[4]*0.6 + sprop[5]*1.2
                    - sprop[6]*1.8 + sprop[7]*1.0;
    x[lane][43]  = (x[lane][32] > 0) ? shadowi * x[lane][32] / 100.0 : 0.0;
    x2[lane][43] = (x2[lane][32] > 0) ? shadowi2 * x2[lane][32] / 100.0 : 0.0;
    ptt_shadowi2[lane] = shadowi2;
    ptt_shadow_loaded[lane] = true;
  }

  // 隐匿标志位
  for (int lane = 0; lane < 4; lane++) if (active & (1u << lane)) {
    if (x[lane][42] > 0) x[lane][44] = 1.0;
    if (x2[lane][42] > 0) x2[lane][44] = 1.0;
  }

  // 护盾>0: 守护→x[45], 原位清零
  for (int lane = 0; lane < 4; lane++) if (active & (1u << lane)) {
    if (x[lane][37] > 0) {
      x[lane][45] = x[lane][26];
      x[lane][26] = 0;
    }
    if (x2[lane][37] > 0) {
      x2[lane][45] = x2[lane][26];
      x2[lane][26] = 0;
    }
  }

  // ---- 二级门 + 每族一阶预筛 (PRE 档 lvl==1 需过共享门; FREE 档 lvl==2 直过) ----
  // ① 共享二级门不过 ⇒ 该 lane 判死; ② 无论 PRE/FREE, 再算每族掩码决定该族是否展开完整模型分。
  // 判据定义在最终 xp_x 上 (含暗影 xp43 / 隐匿 xp44 / 守护 xp45), 故必须在 Step 5 之后求值。
  unsigned fam_mask[4] = {};
  for (int lane = 0; lane < 4; lane++) if (active & (1u << lane)) {
    if (lvl[lane] == 1 && !skill_ok_of(x[lane])) { active &= ~(1u << lane); continue; }
    fam_mask[lane] = fam_pass_mask(pl, x[lane]);
  }
  if (!active) return;

  // 按计划逐 lane 评分 (懒算 poly_1124, 各 lane 独立支持 any 短路)
  for (int lane = 0; lane < 4; lane++) if (active & (1u << lane)) {
    results[lane].sum = sum[lane];
    results[lane].flag = true;
    sp_eval_plan(pl, x[lane], x2[lane], fam_mask[lane], results[lane]);
    results[lane].xp = results[lane].sc[M_QP];
    results[lane].xd = results[lane].sc[M_QD];
  }

  // ---- ptt (potential): 单 name base 变化后的评分上限 (仅用于门控) ----
  if (ptt_any) {
    for (int lane = 0; lane < 4; lane++) if (active & (1u << lane)) {
      bool any_normal_pass = false;
      for (int m = 0; m < M_N; m++) {
        if (score_normal_pass(pl, results[lane], m)) {
          any_normal_pass = true;
          break;
        }
      }
      if (any_normal_pass) continue;
      // 技能候选可能令 x[32] 由 0 变 >0, ptt 需要 SP2 语义 shadowi2; 按需加载暗影号。
      if (!ptt_shadow_loaded[lane]) {
        char shadow_name[260];
        memcpy(shadow_name, names[lane], name_len);
        memcpy(shadow_name + name_len, "?shadow", 8);
        objs[lane].loading_name(shadow_name);
        ptt_shadowi2[lane] = shadowi2_of(objs[lane]);
      }
      for (int m = 0; m < M_N; m++) {
        if (!((fam_mask[lane] >> m) & 1u) || pl.pttv[m] <= 0) continue;
        if (pl.minv[m] > 0 && results[lane].sc[m] >= pl.minv[m]) continue;
        results[lane].sc_max[m] = ptt_score_max(m, ptt_nb[lane], objs[lane].skill,
                                                ptt_last[lane], ptt_f14[lane], ptt_f15[lane],
                                                ptt_shadowi2[lane]);
      }
    }
  }
}
