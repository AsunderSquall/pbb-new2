// ===== Q 门控 (一级判据): 2=FREE 直过 / 1=PRE 待定 / 0=淘汰 =====
// 移植自 src/scoring_sp1.hpp 的 Name::gate_level(), 去掉短号加成 (name_factor ≡ 0,
// 故 sc(v,f)==v)。只依赖 name_base, 可在 calc_skills 之前调用。
//
// 一级判据 = 两张「八维加权纯平面」(F 平面 / R 平面), 由 Pareto 拟合产出
// (见 _gate_refit_fit.py / _gate_refit_fit.out): 正样本 = top-1000 (权重 1/log7(rank)),
// 负样本 = 均匀随机; 解耦拟合 d_lo (FREE 方向) / d_hi (PRE 方向) 后扫阈值取点。
//   放行语义: FREE ⇔ s_F >= θ_F                (level 2, 免检直过)
//             PRE  ⇔ s_R >= θ_R 且非 FREE       (level 1, 需过二级 G3)
//             其余淘汰 (level 0)
//   实测(负样本 2×1e7 + 正样本 2×1000): 保留率 0.010915%, 加权召回 97.51%, top1000 漏 51,
//   FS活跃 0.700%, FREE 0.001%, PRE 0.699%。对比旧生产门: 保留 0.047455% / 召回 94.99% /
//   漏 103 / FS活跃 0.395% ⇒ 放行减少 ≈1/4, 漏减半。(FREE 带缩小 ≈40×, 更安全。)
//
// gate_level_of 顺带把 P1..P7 写进 P[0..6] (即 prop[], 评分本就要用), 不再重复 median;
// 并按旧门控 finish_load_name() 的渐进早退顺序取值, 每级用两平面「剩余维上界」判断是否
// 已必然淘汰(level 0), 命中就直接 return 0, 后面的中位数与 29-CE 排序网络一概不算。
//   旧门控: P7 → (V<24 淘汰) → +P2/P3/P6 → (V<165 淘汰) → +P1/P4/P5 → (V<250 淘汰) → sort10+HP
//   新门控: 同顺序算 P, 早退只决定「省下多少计算」, level 取值与无条件算全版逐位相同。
// 上界依据: 所有写 name_base 的地方都 &63 ⇒ P_i ≤ 63; x0 = 154+b[3..6] ≤ 154+4*63 = 406。
